using System;
using System.IO;
using System.Linq;
using System.Text;
using Hollow.HoUnityTools.Editor.Pmx;

namespace HoPmxDataValidation
{
    internal static class RayValidation
    {
        internal static void RunSynthetic()
        {
            Near(HoPmxRayMaterial.ShininessToSmoothness(30), 0.2928932f, "Ray shininess formula");
            Near(HoPmxRayMaterial.ConvertSmoothness(0.25f, 1), 0.5f, "Squared roughness conversion");
            Near(HoPmxRayMaterial.ConvertSmoothness(0.25f, 2), 0.75f, "Perceptual roughness conversion");
            Near(HoPmxRayMaterial.ApplyScalar(0.25f, 2, 1), 0.5f, "Multiply scale");
            Near(HoPmxRayMaterial.ApplyScalar(0.5f, 2, 2), 0.25f, "Power scale");

            string directory = Path.Combine(Path.GetTempPath(), "HoPmxRaySynthetic-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(directory);
            try
            {
                string pmx = Path.Combine(directory, "test.pmx");
                Write(pmx, "");
                Write(Path.Combine(directory, "Material_MME.emd"), "[Effect]\nObj[0] = root.fx\n");
                Write(Path.Combine(directory, "root.fx"),
                    "// Synthetic source settings; no external shader or model is distributed.\n" +
                    "#define ENABLED 1\n#define BASE (1 + 2)\n" +
                    "#if defined(ENABLED) && BASE == 3\n#define NORMAL_MAP_FROM 0\n#else\n#define NORMAL_MAP_FROM 1\n#endif\n" +
                    "#define METALNESS_MAP_FROM 1\n#define METALNESS_MAP_FILE \"metal.dat\"\n#define METALNESS_MAP_SWIZZLE 2\n" +
                    "#define METALNESS_MAP_APPLY_SCALE 0\nconst float metalness = 0;\n" +
                    "#define SMOOTHNESS_MAP_FROM 9\nconst float smoothness = 0;\n" +
                    "#include \"material_common_2.0.fxsub\"\n");
                Write(Path.Combine(directory, "material_common_2.0.fxsub"),
                    "#ifndef COMMON\n#define COMMON\n" +
                    "float GetSmoothness(); float GetMetalness(); float ShininessToSmoothness();\n" +
                    "#include \"nested.fxsub\"\n#endif\n");
                Write(Path.Combine(directory, "nested.fxsub"), "/* disabled path must not become a dependency */\n#define NORMAL_MAP_FILE \"missing-disabled.png\"\n");
                Write(Path.Combine(directory, "metal.dat"), "synthetic resource marker");

                HoPmxRayDocument result = HoPmxRayReader.Read(pmx);
                Check(result.Materials.Count == 1 && result.Materials[0].RecognizedTemplate, "Known template and material slot");
                Check(result.Materials[0].NormalMapFrom == 0, "Macro condition expression");
                Check(result.Materials[0].MetallicChannel == 2, "Metallic channel");
                Near(result.Materials[0].EvaluateMetallic(0.75f), 0.75f, "Texture replaces zero constant when scale disabled");
                Check(result.Materials[0].SmoothnessFromMaterialPower, "MaterialPower smoothness source");
                Check(result.Dependencies.Count == 5 && result.Dependencies.All(File.Exists), "Nested includes and enabled dependency only");
                Check(result.Warnings.Count == 0, "Synthetic template has no unexpected warnings");

                string other = Path.Combine(directory, "other");
                Directory.CreateDirectory(other);
                Write(Path.Combine(other, "Material_MME.emd"), "[Effect]\nObj[0] = none\n");
                HoPmxRayDocument ambiguous = HoPmxRayReader.Read(pmx);
                Check(ambiguous.Materials.Count == 0 && ambiguous.Warnings.Count == 1, "Multiple EMD files require explicit selection");
                Check(HoPmxRayReader.Read(pmx, "Material_MME.emd").Materials.Count == 1, "Explicit relative EMD resolves ambiguity");

                Write(Path.Combine(other, "unknown.fx"), "#define NORMAL_MAP_FROM 1\n#define NORMAL_MAP_FILE \"not-a-supported-template.png\"\n");
                Write(Path.Combine(other, "Material_MME.emd"), "[Effect]\nObj[0] = unknown.fx\n");
                HoPmxRayDocument unknown = HoPmxRayReader.Read(pmx, Path.Combine(other, "Material_MME.emd"));
                Check(!unknown.Materials[0].RecognizedTemplate && unknown.Materials[0].NormalTexturePath == null, "Unknown FX does not apply guessed material data");
            }
            finally
            {
                // This directory was generated by this run and never points into user assets.
                if (Directory.Exists(directory)) Directory.Delete(directory, true);
            }
            Console.WriteLine("PASS synthetic Ray macros, formulas, dependencies and EMD selection");
        }

        internal static void RunCloudPackage(string path)
        {
            string fullPath = Path.GetFullPath(path);
            Check(File.Exists(fullPath), "PMX sample does not exist: " + fullPath);
            HoPmxRayDocument document = HoPmxRayReader.Read(fullPath);
            HoPmxRayMaterial[] unique = document.Materials.Values.Distinct().ToArray();
            int normals = unique.Count(x => x.NormalTexturePath != null);
            int metallic = unique.Count(x => x.MetallicTexturePath != null);
            int cutouts = unique.Count(x => x.AlphaMode == "Cutout");
            Console.WriteLine("Ray cloud package: slots=" + document.Materials.Count + ", FX=" + unique.Length +
                ", normals=" + normals + ", metallic=" + metallic + ", cutouts=" + cutouts + ", dependencies=" + document.Dependencies.Count);
            Check(document.Materials.Count == 43, "Cloud package must have 43 material slots");
            Check(unique.Length == 25, "Cloud package must have 25 unique FX files");
            Check(normals == 21, "Cloud package must have 21 enabled normal configurations");
            Check(metallic == 20, "Cloud package must have 20 enabled metallic configurations");
            Check(cutouts == 2, "Cloud package must have 2 dedicated Cutout configurations");
            Check(unique.All(x => x.SmoothnessFromMaterialPower), "Cloud smoothness sources must use MaterialPower");
            Check(document.Warnings.Count == 0, "Unexpected cloud package warnings: " + string.Join("; ", document.Warnings));
            Check(document.Dependencies.All(File.Exists), "Enabled cloud dependencies must exist; disabled placeholder paths must be excluded");
            Console.WriteLine("PASS read-only cloud package Ray validation");
        }

        private static void Write(string path, string content) { File.WriteAllText(path, content, new UTF8Encoding(false)); }
        private static void Near(float actual, float expected, string description) { Check(Math.Abs(actual - expected) < 0.000001f, description); }
        private static void Check(bool value, string description) { if (!value) throw new InvalidOperationException(description); }
    }
}
